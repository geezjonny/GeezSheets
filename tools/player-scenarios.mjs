import assert from 'node:assert/strict';
// Identical browser scenarios run against delayed per-client Firebase caches and HTTP/SSE.
export async function playerScenarios(gm,player,sheet){
 const live='geezvtt/live/world__daddies/',party='geezvtt/party/world__daddies/';
 const write=(page,path,value)=>page.evaluate(({path,value})=>window.__SHEETS__.database().ref(path).set(value),{path,value});
 const read=(page,path)=>page.evaluate(async path=>(await window.__SHEETS__.database().ref(path).once('value')).val(),path);
 const seen=(path,check)=>gm.waitForFunction(async({path,check})=>{const v=(await window.__SHEETS__.database().ref(path).once('value')).val();return JSON.stringify(v)?.includes(check);},{path,check});
 const denied=async(page,path,value)=>{await page.waitForTimeout(150);assert.equal(await page.evaluate(async({path,value})=>{try{await window.__SHEETS__.database().ref(path).set(value);return 'allowed';}catch(e){return e.status||e.message;}},{path,value}),403,path);};
 await player.waitForFunction(()=>document.querySelector('#playerNameLabel')?.textContent==='Ashara');
 await gm.waitForFunction(async()=>(await window.__SHEETS__.database().ref('geezvtt/live/world__daddies/presence/p_Ashara').once('value')).val()?.dm===false);
 console.log('PASS URL-selected player reports its own presence automatically');
 const ids=await player.evaluate(()=>window.__SHEETS__.database().ids()),noteTarget=ids.newToOld[ids.oldToNew.ashara];
 const roll={by:'Ashara',char:'ashara',expr:'1d20',detail:'[12]',total:12,nat:12,dice:[{s:20,v:12}],ts:Date.now()};
 await write(player,live+'rolls/player_test',roll);await seen(live+'rolls/player_test','Ashara');
 await denied(player,live+'rolls/player_test',{...roll,total:20});await denied(player,live+'rolls/player_test',null);
 await denied(player,live+'rolls/spoof',{...roll,by:'Liora',char:'liora'});
 // The actual player sheet button logs a roll and sets the PC's initiative row.
 await sheet.evaluate(()=>window.rollInitiative('ashara'));
 await gm.waitForFunction(async()=>Object.values((await window.__SHEETS__.database().ref('geezvtt/live/world__daddies/rolls').once('value')).val()||{}).some(r=>r.by==='Ashara'&&r.expr==='Initiative'));
 console.log('PASS player page/sheet rolls reach GM live; spoofing, modification and deletion rejected');
 const ping={v:'DM_BOARD:world__daddies',x:.3,y:.4,by:'Ashara',f:0,ts:Date.now()};
 await write(player,live+'pings/player_test',ping);await seen(live+'pings/player_test','Ashara');
 await write(player,live+'pings/player_test',null);
 await write(gm,live+'pings/gm_test',{...ping,by:'DM'});await denied(player,live+'pings/gm_test',null);
 await write(gm,live+'session/lockPings',true);await denied(player,live+'pings/locked',ping);await write(gm,live+'session/lockPings',false);
 await write(player,live+'presence/p_Ashara',{name:'Ashara',dm:false,where:'Player test',level:'DM_BOARD',t:Date.now()});
 await seen(live+'presence/p_Ashara','Player test');
 await denied(player,live+'presence/p_Liora',{name:'Liora',dm:false,where:'spoof'});
 await denied(player,live+'presence/p_Ashara',{name:'Ashara',dm:true});
 console.log('PASS owned ping creation/cleanup, GM ping protection, ping lock and live presence');
 await write(gm,live+'rollcall',{id:'test_call',kind:'save',key:'dex',title:'Test save',mode:'normal',open:true,to:{ashara:'Ashara',liora:'Liora'},t:Date.now()});
 await sheet.locator('#rollCall fieldset[data-id="ashara"] button').click();
 await sheet.waitForFunction(()=>document.querySelector('#rollCall')?.textContent.includes('Ashara:'));
 await seen(live+'rollcall/results/ashara','Ashara');
 const answer=await read(gm,live+'rollcall/results/ashara');assert.ok(answer,'rollcall answer must persist');
 await denied(player,live+'rollcall/results/ashara',{...answer,total:99});
 await denied(player,live+'rollcall/results/liora',{...answer,name:'Liora',charId:'liora'});
 await write(gm,live+'rollcall/open',false);await denied(player,live+'rollcall/results/ashara',{...answer,total:98});
 await write(gm,live+'rollcall',{id:'replacement',kind:'save',key:'dex',mode:'normal',open:true,to:{ashara:'Ashara'}});
 await player.waitForFunction(async()=>(await window.__SHEETS__.database().ref('geezvtt/live/world__daddies/rollcall').once('value')).val()?.id==='replacement');
 await denied(player,live+'rollcall/results/ashara',answer);
 console.log('PASS GM rollcall answered from sheet, first answer wins; foreign, closed and stale answers rejected');
 const init=await read(player,live+'initiative');
 const id=Object.keys(init.rows).find(id=>init.rows[id].charId==='ashara');assert.ok(id);
 await write(player,live+'initiative/rows/'+id,{...init.rows[id],init:19});
 await seen(live+'initiative/rows/'+id,'19');
 await write(gm,live+'initiative/rows/foreign',{name:'Liora',charId:'liora',init:9});
 await denied(player,live+'initiative/rows/foreign',{name:'Liora',charId:'liora',init:22});
 await denied(player,live+'initiative/round',99);
 await denied(player,live+'initiative/rows/'+id,{name:'Liora',charId:'liora',init:22});
 console.log('PASS own initiative edits preserve GM controls and reject foreign rows/entity substitution');
 const note={author:'Ashara',text:'Friday notes',ts:Date.now()};
 await write(player,party+'notes/'+noteTarget+'/player_test',note);await seen(party+'notes/'+noteTarget+'/player_test','Friday notes');
 await write(player,party+'notes/'+noteTarget+'/player_test',{...note,text:'Updated'});
 await denied(player,party+'notes/'+noteTarget+'/spoof',{...note,author:'Liora'});
 await write(gm,party+'notes/'+noteTarget+'/foreign',{author:'Liora',text:'Foreign',owner:'not-ashara'});
 await denied(player,party+'notes/'+noteTarget+'/foreign',note);await denied(player,party+'notes/'+noteTarget+'/foreign',null);
 await write(player,party+'notes/'+noteTarget+'/player_test',null);
 await write(player,party+'cards/player_card',{id:'player_card',type:'note',name:'My clue',notes:'test',traits:{},board:{x:10,y:20}});
 await write(player,party+'cards/player_card/name','My revised clue');
 assert.ok(Object.values(await read(player,party+'cards')).every(card=>typeof card.name==='string'),'transport markers must never appear as party cards');
 await write(player,party+'board/player_card',{x:20,y:30});
 await write(player,party+'links/player_link',{id:'player_link',from:'player_card',to:'ashara',label:'reminds me'});
 await write(gm,party+'cards/foreign_card',{id:'foreign_card',type:'note',name:'GM card'});
 await denied(player,party+'cards/foreign_card/name','Hijacked');
 await write(player,party+'links/player_link',null);await write(player,party+'cards/player_card',null);
 assert.equal(await player.evaluate(async path=>{try{await window.__SHEETS__.database().ref(path).set({author:'Ashara',text:'x'.repeat(4001)});return 'allowed';}catch(e){return e.status;}},party+'notes/'+noteTarget+'/oversize'),400);
 await denied(player,'geezvtt/live/world__disney/rolls/cross_campaign',roll);
 await denied(player,live+'audio',{track:'forbidden'});await denied(player,live+'session/lockMove',true);
 console.log('PASS owned notes/cards/strings/layout, ownership protection, text limits, campaign isolation and GM-only controls');
 // GM can still replace/clear every new player record through the ordinary state/app routes.
 await write(gm,live+'rolls/player_test',null);await write(gm,live+'presence/p_Ashara',null);
 await write(gm,party+'cards/foreign_card',null);await write(gm,live+'rollcall',null);
 await player.reload({waitUntil:'domcontentloaded'});await player.waitForFunction(()=>window.__SHEETS__?.state().data.pcs.ashara);
 assert.equal((await read(player,live+'initiative/rows/'+id)).init,19);
 console.log('PASS GM retains full control; player reload preserves own initiative');
}
